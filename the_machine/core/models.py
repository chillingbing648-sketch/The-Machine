@dataclass
class ValidationResult:
    """Result of evaluating a patch candidate against the validation suite."""
    status: ValidationStatus
    failing_test_passed: bool
    regression_tests_passed: bool
    syntax_valid: bool
    anti_pattern_detected: bool
    message: str
    failing_test_report: Optional[TestExecutionReport] = None
    regression_test_report: Optional[TestExecutionReport] = None
    execution_time_sec: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "status": self.status.value,
            "failing_test_passed": self.failing_test_passed,
            "regression_tests_passed": self.regression_tests_passed,
            "syntax_valid": self.syntax_valid,
            "anti_pattern_detected": self.anti_pattern_detected,
            "message": self.message,
            "failing_test_report": self.failing_test_report.to_dict() if self.failing_test_report else None,
            "regression_test_report": self.regression_test_report.to_dict() if self.regression_test_report else None,
            "execution_time_sec": self.execution_time_sec,
        }


@dataclass
class ExperimentSummary:
    """Comprehensive summary of a repair experiment run."""
    experiment_id: str
    status: ExperimentStatus
    target_name: str
    config: ExperimentConfig
    mutation: Optional[MutationRecord] = None
    baseline_report: Optional[TestExecutionReport] = None
    suspicious_locations: List[SuspiciousLocation] = field(default_factory=list)
    localization_metrics: Optional[LocalizationMetrics] = None
    candidates_evaluated: int = 0
    accepted_patch: Optional[PatchCandidate] = None
    accepted_validation: Optional[ValidationResult] = None
    total_duration_sec: float = 0.0
    created_at: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "experiment_id": self.experiment_id,
            "status": self.status.value,
            "target_name": self.target_name,
            "config": self.config.to_dict(),
            "mutation": self.mutation.to_dict() if self.mutation else None,
            "baseline_report": self.baseline_report.to_dict() if self.baseline_report else None,
            "suspicious_locations": [loc.to_dict() for loc in self.suspicious_locations],
            "localization_metrics": self.localization_metrics.to_dict() if self.localization_metrics else None,
            "candidates_evaluated": self.candidates_evaluated,
            "accepted_patch": self.accepted_patch.to_dict() if self.accepted_patch else None,
            "accepted_validation": self.accepted_validation.to_dict() if self.accepted_validation else None,
            "total_duration_sec": self.total_duration_sec,
            "created_at": self.created_at,
        }
