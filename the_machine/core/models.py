"""Data models for The Machine program repair and reliability engine."""

from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import Dict, List, Optional, Any
import json
import time
import uuid


class ValidationStatus(str, Enum):
    """Validation outcome categories."""
    ACCEPTED = "ACCEPTED"
    REJECTED = "REJECTED"
    REGRESSED = "REGRESSED"
    SYNTAX_ERROR = "SYNTAX_ERROR"
    TIMEOUT = "TIMEOUT"
    ANTI_PATTERN = "ANTI_PATTERN"


class ExperimentStatus(str, Enum):
    """Experiment lifecycle status."""
    INITIALIZED = "INITIALIZED"
    INJECTED = "INJECTED"
    FAILED_DETECTED = "FAILED_DETECTED"
    LOCALIZED = "LOCALIZED"
    REPAIRED = "REPAIRED"
    UNRESOLVED = "UNRESOLVED"
    ERROR = "ERROR"


@dataclass
class ExperimentConfig:
    """Configuration parameters for an automated repair experiment."""
    target_name: str
    target_rel_path: str
    test_rel_path: str
    timeout_sec: float = 10.0
    random_seed: int = 42
    max_candidates: int = 10
    enabled_strategies: List[str] = field(default_factory=lambda: ["deterministic_template", "search_ast"])

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ExperimentConfig":
        return cls(**data)


